# i) Install Python

# ii) Create Virtual Environment using cmd: python -m venv environmentName

# iii) Activate Venv using .\environmentName\Scripts\Activate.ps1

# iv) Install Django inside venv using: python -m pip install Django

# v) Check Django version: python -m django --version

# vi) Create Project: python -m django startproject ProjectName

# vii) change directory to newly created project and run server:

#             ->  cd myproject [ command to change directory ]
#             -> python manage.py runserver  [ command to run server ]

# viii) Ctrl + c to stop the server

# ix) Create App: python -m django startapp appName

# enter deactivate command to close venv